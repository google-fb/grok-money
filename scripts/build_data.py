def validate(rows, key):
    assert len(rows) == 100, f"{key} has {len(rows)}"
    nows = [r["now"] for r in rows]
    preds = [r["pred"] for r in rows]
    assert sorted(nows) == list(range(1, 101)), f"{key} now ranks broken: {sorted(nows)}"
    assert sorted(preds) == list(range(1, 101)), f"{key} pred ranks broken {sorted(preds)}"
    ids = [r["id"] for r in rows]
    assert len(set(ids)) == 100


