    base = [cid for cid in raw if cid not in NOW_INSERTS]
    cut = base.index("c30")
    now_order = base[:cut] + NOW_INSERTS + base[cut:]
    apply_order(rows, now_order, "now")
    apply_order(rows, PRED_ORDER, "pred")


